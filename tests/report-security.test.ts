import { licensed } from './merkez-fixture.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'node:http';
import type { AddressInfo } from 'node:net';
import { Store } from '../server/store.js';
import { createApp, DEMO_PASSWORD } from '../server/app.js';
import { totp } from '../server/totp.js';
test('MFA enforces report and adjustment access per session, expiry, replay and recovery', async t => {
  mkdirSync('.local/tests', { recursive: true }); const store = new Store(mkdtempSync(resolve('.local/tests/mfa-')));
  let time = Date.now(); licensed(store); const server = createServer(createApp(store, () => new Date(time)));
  await new Promise<void>(r => server.listen(0, '127.0.0.1', r));
  t.after(async () => { server.closeAllConnections(); await new Promise<void>(r => server.close(() => r())); store.close(); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}/api`;
  function client() { let cookie = ''; return async (path: string, body?: unknown) => { const r = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers: { 'Content-Type': 'application/json', Cookie: cookie }, body: body === undefined ? undefined : JSON.stringify(body) }); if (r.headers.getSetCookie().length) cookie = r.headers.getSetCookie()[0].split(';')[0]; return { status: r.status, data: await r.json() as any }; }; }
  const owner = client(), second = client(), waiter = client();
  for (const call of [owner, second]) assert.equal((await call('/login', { username: 'isletme', password: DEMO_PASSWORD })).status, 200);
  await waiter('/login', { username: 'garson', password: DEMO_PASSWORD });
  assert.equal((await waiter('/staff/report-security')).status, 403);
  assert.equal((await waiter('/staff/photo-trash', {})).status, 403);
  assert.equal((await owner('/staff/report-security/setup', { password: 'wrong' })).status, 403);
  const setup = await owner('/staff/report-security/setup', { password: DEMO_PASSWORD }); assert.equal(setup.status, 200);
  const enabled = await owner('/staff/report-security/enable', { code: totp(setup.data.secret, time) }); assert.equal(enabled.status, 200); assert.equal(enabled.data.recoveryCodes.length, 8);
  const loginClient = client();
  assert.equal((await loginClient('/login', { username: 'isletme', password: 'wrong' })).data.code, 'INVALID_LOGIN');
  assert.equal((await loginClient('/login', { username: 'isletme', password: DEMO_PASSWORD })).data.code, 'MFA_REQUIRED');
  assert.equal((await loginClient('/staff/state')).status, 401);
  assert.equal((await loginClient('/login', { username: 'isletme', password: DEMO_PASSWORD, code: 'wrong' })).status, 403);
  assert.equal((await loginClient('/login', { username: 'isletme', password: DEMO_PASSWORD, code: enabled.data.recoveryCodes[7] })).status, 200);
  assert.equal((await client()('/login', { username: 'isletme', password: DEMO_PASSWORD, code: enabled.data.recoveryCodes[7] })).status, 403);
  assert.equal((await second('/staff/payment-adjustments')).status, 403); assert.equal((await owner('/staff/payment-adjustments')).status, 200);
  assert.equal((await second('/staff/report-security/verify', { code: totp(setup.data.secret, time) })).status, 403);
  time += 30000;
  assert.equal((await second('/staff/report-security/verify', { code: totp(setup.data.secret, time) })).status, 200);
  assert.equal((await second('/staff/reports/financial?from=2026-09-21&to=2026-09-21')).status, 200);
  const staff = await owner('/staff/users'); assert.equal(JSON.stringify(staff.data).includes(setup.data.secret), false);
  time += 601000; assert.equal((await owner('/staff/payment-adjustments', {})).status, 403);
  assert.equal((await owner('/staff/reports/financial?from=2026-09-21&to=2026-09-21')).status, 403);
  assert.equal((await owner('/staff/report-security/recover', { password: DEMO_PASSWORD, recoveryCode: '0'.repeat(32) })).status, 403);
  assert.equal((await owner('/staff/report-security/recover', { password: DEMO_PASSWORD, recoveryCode: enabled.data.recoveryCodes[0] })).status, 200);
  assert.equal((await owner('/staff/report-security')).data.enabled, false);
  assert.equal((await owner('/staff/report-security/recover', { password: DEMO_PASSWORD, recoveryCode: enabled.data.recoveryCodes[0] })).status, 403);
});
