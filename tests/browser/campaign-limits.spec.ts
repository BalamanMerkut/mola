import { test, expect } from '@playwright/test';
import { ensureSetup, openView } from './helpers';

test('campaign quota shows live usage, expires automatically and releases cancelled units', async ({ page, browser }, info) => {
  await page.request.post('/api/login', { data: { username: 'isletme', password: 'MolaDemo!2026' } }); await ensureSetup(page.request);
  const initial = await (await page.request.get('/api/staff/state')).json();
  const table = initial.tables.filter((t: any) => !t.account && !t.needsCleaning).at(-1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/'); await openView(page, 'Kampanyalar');
  await page.getByRole('button', { name: 'Kampanya ekle', exact: true }).click();
  const editor = page.getByRole('dialog');
  await editor.getByLabel('Kampanya adı').fill('Sınırlı çay');
  await editor.getByLabel('İndirim türü').selectOption('fixed');
  await editor.getByLabel('İndirim tutarı (TL)').fill('10');
  await editor.getByRole('checkbox', { name: 'Toplam adet sınırı koy' }).check();
  await expect(editor.getByLabel('Kampanya kaç adetle sınırlı?')).toHaveValue('50');
  await editor.getByLabel('Kampanya kaç adetle sınırlı?').fill('0');
  await expect(editor.getByRole('button', { name: 'Kampanyayı kaydet' })).toBeDisabled();
  await editor.getByLabel('Kampanya kaç adetle sınırlı?').fill('2');
  await editor.getByRole('button', { name: /Menüden seç/ }).click();
  const picker = page.getByRole('dialog', { name: 'Menüden kampanya ürünü seç' });
  await picker.getByRole('button', { name: /Demleme Çay/ }).click();
  await picker.getByRole('button', { name: /Seçimi tamamla/ }).click();
  await editor.getByLabel('Kampanya kaç adetle sınırlı?').scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('quota-editor-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await editor.getByRole('button', { name: 'Kampanyayı kaydet' }).click();
  const card = page.locator('.campaign-card').filter({ hasText: 'Sınırlı çay' });
  await expect(card).toContainText('0 / 2 adet');
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  try {
    const guest = await context.newPage(); await guest.goto(`/m/${table.token}`);
    const product = guest.getByRole('button', { name: /Demleme Çay/ });
    await product.click(); await expect(guest.getByRole('dialog')).toContainText('Kampanyada kalan: 2 adet');
    await guest.getByRole('button', { name: 'Adedi artır' }).click(); await guest.getByRole('button', { name: 'Adedi artır' }).click();
    await guest.getByRole('button', { name: /Sepete ekle/ }).click();
    await guest.getByRole('button', { name: /Sepet(imi|i) görüntüle/ }).click();
    await guest.getByRole('button', { name: 'Siparişi gönder', exact: true }).click();
    await expect(guest.getByRole('dialog')).toContainText('2 adet yer kaldı');
    await guest.getByRole('button', { name: 'Ürünü kaldır' }).click();
    await guest.getByRole('dialog').getByRole('button', { name: 'Kapat', exact: true }).click();
    await product.click(); await guest.getByRole('button', { name: 'Adedi artır' }).click();
    await guest.getByRole('button', { name: /Sepete ekle/ }).click();
    await guest.getByRole('button', { name: /Sepet(imi|i) görüntüle/ }).click();
    await guest.getByRole('button', { name: 'Siparişi gönder', exact: true }).click();
    await guest.getByRole('button', { name: 'Tamam', exact: true }).click();
    await expect(card).toContainText('2 / 2 adet', { timeout: 10000 });
    await expect(card).toContainText('Adet sınırı doldu');
    await expect(product).toContainText('₺35');
    await page.screenshot({ path: info.outputPath('quota-complete-mobile.png') });
    await card.getByRole('button', { name: 'Kampanyayı düzenle' }).click();
    await editor.getByLabel('Kampanya kaç adetle sınırlı?').fill('1');
    await expect(editor.getByRole('button', { name: 'Kampanyayı kaydet' })).toBeDisabled();
    await editor.getByLabel('Kampanya kaç adetle sınırlı?').fill('2');
    await editor.getByRole('button', { name: 'Kampanyayı kaydet' }).click();
    await expect(card).toContainText('2 / 2 adet');
    const state = await (await page.request.get('/api/staff/state')).json();
    const order = state.orders.find((o: any) => o.tableName === table.name && !initial.orders.some((old: any) => old.id === o.id));
    expect((await page.request.post('/api/staff/orders/cancel', { data: { requestId: crypto.randomUUID(), orderId: order.id, version: order.version, reason: 'Müşteri vazgeçti' } })).ok()).toBe(true);
    await expect(card).toContainText('0 / 2 adet', { timeout: 10000 });
    await expect(product).toContainText('₺25');
    await card.getByRole('button', { name: 'Kampanyayı düzenle' }).click();
    await editor.getByRole('checkbox', { name: 'Kampanya etkin', exact: true }).uncheck();
    await editor.getByRole('button', { name: 'Kampanyayı kaydet' }).click();
  } finally { await context.close(); }
});
