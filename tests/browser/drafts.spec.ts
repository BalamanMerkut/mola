import { test, expect } from '@playwright/test';
import { ensureSetup } from './helpers';

test('incomplete draft survives lost response and is hidden until published', async ({ page, browser }, info) => {
  await page.request.post('/api/login', { data: { username: 'isletme', password: 'MolaDemo!2026' } }); await ensureSetup(page.request);
  const state = await (await page.request.get('/api/staff/state')).json();
  const context = await browser.newContext();
  try {
    const guest = await context.newPage(); await guest.goto(`/m/${state.tables[0].token}`);
    await page.goto('/'); await page.getByRole('button', { name: 'Menü yönetimi', exact: true }).click();
    await page.getByRole('button', { name: 'Ürün ekle', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('Ürün adı', { exact: true }).fill('Pilot taslak latte');
    await expect(dialog.getByRole('button', { name: 'Kaydet ve yayınla', exact: true })).toBeDisabled();
    await page.route('**/api/staff/products', async route => { await route.fetch(); await route.abort('failed'); await page.unroute('**/api/staff/products'); });
    await dialog.getByRole('button', { name: 'Taslak kaydet', exact: true }).click();
    await expect(dialog.getByLabel('Ürün adı', { exact: true })).toBeDisabled();
    await dialog.getByRole('button', { name: 'Kaydı yeniden kontrol et', exact: true }).click();
    await expect(dialog).toHaveCount(0);
    const row = page.locator('.menu-row').filter({ hasText: 'Pilot taslak latte' });
    await expect(row).toContainText('Taslak'); await expect(row).toHaveCount(1);
    await expect(guest.getByRole('button', { name: /Pilot taslak latte/ })).toHaveCount(0);
    await page.getByRole('button', { name: 'Menüyü önizle', exact: true }).click();
    await expect(page.frameLocator('iframe').getByText('Pilot taslak latte', { exact: true })).toHaveCount(0);
    await page.getByRole('dialog').getByRole('button', { name: /Kapat/ }).click();
    await row.getByRole('button', { name: 'Düzenle', exact: true }).click();
    await dialog.getByLabel('Kategori', { exact: true }).selectOption('Kahveler');
    await dialog.getByLabel('Fiyat (TL)', { exact: true }).fill('95');
    await page.screenshot({ path: info.outputPath('draft-editor.png'), fullPage: true });
    await dialog.getByRole('button', { name: 'Kaydet ve yayınla', exact: true }).click();
    await expect(row).toContainText('Yayında');
    await expect(guest.getByRole('button', { name: /Pilot taslak latte/ })).toBeVisible();
    await guest.getByRole('button', { name: /Pilot taslak latte/ }).click();
    await guest.getByRole('button', { name: /Sepete ekle/ }).click();
    await guest.getByRole('button', { name: /Sepet(imi|i) görüntüle/ }).click();
    await guest.getByRole('button', { name: 'Siparişi gönder', exact: true }).click();
    await guest.getByRole('button', { name: 'Tamam', exact: true }).click();
    await row.getByRole('button', { name: 'Düzenle', exact: true }).click();
    await dialog.getByLabel('Ürün adı', { exact: true }).fill('Yenilenmiş latte');
    await dialog.getByLabel('Fiyat (TL)', { exact: true }).fill('125');
    await page.route('**/api/staff/products', async route => { await route.fetch(); await route.abort('failed'); await page.unroute('**/api/staff/products'); });
    await dialog.getByRole('button', { name: 'Taslağa al', exact: true }).click();
    await dialog.getByRole('button', { name: 'Kaydı yeniden kontrol et', exact: true }).click();
    const updated = page.locator('.menu-row').filter({ hasText: 'Yenilenmiş latte' });
    await expect(updated).toContainText('Taslak');
    await expect(updated).not.toContainText('Yayında');
    await expect(guest.getByRole('button', { name: /Pilot taslak latte/ })).toHaveCount(0);
    await expect(guest.getByRole('button', { name: /Yenilenmiş latte/ })).toHaveCount(0);
    const after = await (await page.request.get('/api/staff/state')).json();
    expect(after.productDrafts).toHaveLength(0);
    expect(after.orders.find((o: any) => o.lines.some((l: any) => l.name === 'Pilot taslak latte')).total).toBe(9500);
    await updated.getByRole('button', { name: 'Düzenle', exact: true }).click();
    await expect(dialog.getByLabel('Ürün adı', { exact: true })).toHaveValue('Yenilenmiş latte');
    await expect(dialog.getByLabel('Fiyat (TL)', { exact: true })).toHaveValue('125');
    await dialog.getByRole('button', { name: 'Kaydet ve yayınla', exact: true }).click();
    await expect(updated).toContainText('Yayında');
    await expect(guest.getByRole('button', { name: /Yenilenmiş latte/ })).toBeVisible();
  } finally { await context.close(); }
});
