import { test, expect } from '@playwright/test';
import { ensureSetup, openSettings, openView } from './helpers';
test('custom table areas, product/campaign removal and compact settings/employee cards', async ({ page }, info) => {
 await page.request.post('/api/login',{data:{username:'isletme',password:'MolaDemo!2026'}}); await ensureSetup(page.request);
 await page.goto('/');
 await page.getByRole('button',{name:'Masa ekle',exact:true}).click();
 await page.getByRole('button',{name:'Yeni +',exact:true}).click();
 await page.getByRole('textbox',{name:'Yeni bölüm adı'}).fill('Üst kat');
 await page.getByRole('button',{name:'Bölümü seç'}).click();
 await expect(page.getByRole('button',{name:'Üst kat',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'Yeni masayı oluştur'}).click();
 await expect(page.getByRole('heading',{name:'Üst kat masaları',exact:true})).toBeVisible();
 await page.reload(); await expect(page.getByRole('heading',{name:'Üst kat masaları',exact:true})).toBeVisible();
 const state=await (await page.request.get('/api/staff/state')).json();
 expect(state.tables.some((t:any)=>t.area==='Üst kat')).toBe(true);
 await page.getByRole('button',{name:'Menü yönetimi',exact:true}).click();
 const row=page.locator('.menu-row').first(); const productName=await row.locator('h3').innerText();
 await row.getByRole('button',{name:'Düzenle',exact:true}).click();
 await page.getByRole('dialog',{name:'Ürünü düzenle'}).screenshot({path:info.outputPath('product-actions.png')});
 await page.getByRole('button',{name:'Ürünü sil',exact:true}).click();
 await page.getByRole('dialog',{name:'Ürünü sil',exact:true}).getByRole('button',{name:'Vazgeç',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Ürünü düzenle'})).toBeVisible();
 await page.getByRole('button',{name:'Ürünü sil',exact:true}).click();
 await page.route('**/api/staff/catalog/remove',async route=>{ const response=await route.fetch(); expect(response.ok()).toBe(true); await route.abort(); });
 await page.getByRole('button',{name:'Evet, sil',exact:true}).click();
 await expect(page.getByRole('button',{name:'Silme işlemini yeniden kontrol et'})).toBeVisible();
 await page.unroute('**/api/staff/catalog/remove');
 await page.getByRole('button',{name:'Silme işlemini yeniden kontrol et'}).click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.locator('.menu-row h3').filter({hasText:productName})).toHaveCount(0);
 const after=await (await page.request.get('/api/staff/state')).json();
 const created=await page.request.post('/api/staff/campaigns',{data:{requestId:'cards-campaign',revision:after.revision,campaign:{name:'Biten deneme kampanyası',percent:10,productIds:[after.products[0].id],startsAt:'2020-01-01T00:00:00Z',endsAt:'2020-01-02T00:00:00Z',enabled:true,combine:false}}}); expect(created.ok()).toBe(true);
 await page.getByRole('button',{name:'Kampanyalar',exact:true}).click();
 // Finished campaigns are folded under "Biten kampanyalar" below the running and upcoming ones.
 await page.getByText('Biten kampanyalar (1)',{exact:true}).click();
 await expect(page.locator('.campaign-card')).toContainText('Sona erdi');
 await expect(page.locator('.campaign-card')).toContainText('Bitiş: 2 Oca 2020 03:00');
 await page.getByRole('button',{name:'Kampanyayı düzenle',exact:true}).click();
 await page.getByRole('dialog',{name:'Kampanyayı düzenle'}).screenshot({path:info.outputPath('campaign-editor.png')});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Kampanyayı sil',exact:true}).scrollIntoViewIfNeeded();
 await page.getByRole('dialog',{name:'Kampanyayı düzenle'}).screenshot({path:info.outputPath('campaign-editor-mobile.png')});
 await page.getByRole('button',{name:'Kampanyayı sil',exact:true}).click();
 await page.getByRole('button',{name:'Evet, sil',exact:true}).click();
 await expect(page.locator('.campaign-card')).toHaveCount(0);
 await openSettings(page,'Sipariş ve onay');
 // Ödeme sırası, the change window switch and its seconds, QR approval, automatic approval (POS commission: Kasa ve giderler → Kasa ayarları).
 await expect(page.locator('.settings-row')).toHaveCount(5); // garson ataması moved to Personel → Personel ayarları (10 Ekim)
 await page.setViewportSize({width:1280,height:900});
 await openSettings(page,'Cihazlar');
 await page.locator('.photo-storage > summary').click();
 await expect(page.getByText('Kullanılan alan',{exact:true})).toBeVisible();
 await page.locator('.photo-storage').screenshot({path:info.outputPath('photo-storage-open.png')});
 await page.screenshot({path:info.outputPath('settings-cards.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('settings-cards-mobile.png'),fullPage:true});
 await openView(page,'Çalışanlar');
 await expect(page.locator('.employee-row').first()).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:info.outputPath('employee-cards-mobile.png'),fullPage:true});
});
